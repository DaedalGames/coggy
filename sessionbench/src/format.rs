//! Rendering shared by every report.

/// Bytes at one decimal place, in the binary units the rest of the report uses.
///
/// Binary throughout, matching how memory is reported: the RSS condition is a
/// fraction of physical memory, and mixing GB into that arithmetic moves a
/// verdict by 7%.
pub fn human_bytes(bytes: u64) -> String {
    const UNITS: [&str; 5] = ["B", "KiB", "MiB", "GiB", "TiB"];
    let mut value = bytes as f64;
    let mut unit = 0;
    while value >= 1024.0 && unit < UNITS.len() - 1 {
        value /= 1024.0;
        unit += 1;
    }
    if unit == 0 {
        format!("{bytes} B")
    } else {
        format!("{value:.1} {}", UNITS[unit])
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bytes_render_in_binary_units() {
        assert_eq!(human_bytes(512), "512 B");
        assert_eq!(human_bytes(1024), "1.0 KiB");
        assert_eq!(human_bytes(33_707_749_376), "31.4 GiB");
    }
}
